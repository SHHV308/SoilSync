CREATE TABLE plants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    variety VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    soil_type VARCHAR(255) NOT NULL,
    notes VARCHAR(1200),
    health_status VARCHAR(255) NOT NULL,
    last_watered_at TIMESTAMP NOT NULL,
    next_watering_at TIMESTAMP NOT NULL
);

CREATE TABLE care_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT NOT NULL REFERENCES plants(id),
    type VARCHAR(255) NOT NULL,
    note VARCHAR(1200),
    occurred_at TIMESTAMP NOT NULL
);

CREATE TABLE reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT NOT NULL REFERENCES plants(id),
    type VARCHAR(255) NOT NULL,
    due_at TIMESTAMP NOT NULL,
    status VARCHAR(255) NOT NULL,
    notes VARCHAR(1200)
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(255) NOT NULL,
    price DOUBLE PRECISION NOT NULL,
    description VARCHAR(1200),
    unit VARCHAR(255) NOT NULL,
    stock INTEGER NOT NULL,
    recommended_use VARCHAR(800)
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(255) NOT NULL,
    total_amount DOUBLE PRECISION NOT NULL,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    product_name VARCHAR(255) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price DOUBLE PRECISION NOT NULL
);

CREATE TABLE privacy_consents (
    id UUID PRIMARY KEY,
    consented_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consent_version VARCHAR(40) NOT NULL
);

CREATE TABLE advisory_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consent_id UUID NOT NULL REFERENCES privacy_consents(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    country_code VARCHAR(2),
    region VARCHAR(120),
    crop VARCHAR(120) NOT NULL,
    growth_stage VARCHAR(80) NOT NULL,
    soil_type VARCHAR(100) NOT NULL,
    weather_snapshot VARCHAR(2000) NOT NULL,
    risk_flag BOOLEAN NOT NULL,
    question VARCHAR(2000),
    answer VARCHAR(8000) NOT NULL,
    sources VARCHAR(6000) NOT NULL,
    feedback VARCHAR(20),
    application_outcome VARCHAR(30) NOT NULL DEFAULT 'UNKNOWN',
    CONSTRAINT advisory_logs_feedback_check
        CHECK (feedback IS NULL OR feedback IN ('HELPFUL', 'NOT_HELPFUL')),
    CONSTRAINT advisory_logs_outcome_check
        CHECK (application_outcome IN ('DEFERRED_APPLICATION', 'APPLIED_ANYWAY', 'UNKNOWN'))
);

CREATE INDEX advisory_logs_consent_created_idx ON advisory_logs(consent_id, created_at);
CREATE INDEX advisory_logs_region_crop_idx ON advisory_logs(country_code, region, crop);
