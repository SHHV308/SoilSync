CREATE TABLE chat_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consent_id UUID NOT NULL REFERENCES privacy_consents(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    country_code VARCHAR(2),
    region VARCHAR(120),
    crop VARCHAR(120),
    growth_stage VARCHAR(80),
    soil_type VARCHAR(100),
    weather_snapshot VARCHAR(2000),
    risk_flag BOOLEAN NOT NULL,
    question VARCHAR(2000) NOT NULL,
    answer VARCHAR(8000) NOT NULL,
    sources VARCHAR(6000) NOT NULL,
    feedback VARCHAR(20),
    application_outcome VARCHAR(30) NOT NULL DEFAULT 'UNKNOWN',
    CONSTRAINT chat_logs_feedback_check
        CHECK (feedback IS NULL OR feedback IN ('HELPFUL', 'NOT_HELPFUL')),
    CONSTRAINT chat_logs_outcome_check
        CHECK (application_outcome IN ('DEFERRED_APPLICATION', 'APPLIED_ANYWAY', 'UNKNOWN'))
);

CREATE INDEX chat_logs_consent_created_idx ON chat_logs(consent_id, created_at);
CREATE INDEX chat_logs_region_crop_idx ON chat_logs(country_code, region, crop);
